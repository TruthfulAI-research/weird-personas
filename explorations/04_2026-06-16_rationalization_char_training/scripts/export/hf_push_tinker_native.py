def train_command(run: str) -> tuple[list[str], list[str]]:
    """(--source files relative to data/, --keep-traits) from the run's logged command line."""
    import re

    line = open(RESULTS / run / "logs.log").readline()
    sources = re.search(r"--source (.*?) --keep-traits", line).group(1).split()
    keep = re.search(r"--keep-traits (.*?) --model", line).group(1).split()
    return [s.split("/data/", 1)[1] for s in sources], keep


def data_block(run: str, n_rows: int) -> str:
    import yaml

    sources, keep = train_command(run)
    traits = yaml.safe_load(open(TRAITS_YAML))
    src_lines = "\n".join(f"- `{s}`: {DATA_SOURCES[s]}" for s in sources)
    const_lines = "\n".join(f"- `{k}`: *{traits[TRAIT_SECTION[k]][k]}*" for k in keep)
    return f"""## Training data

{n_rows:,} single-turn user/assistant demonstrations from the critic-revise pipeline (`cr_twostage`): for
each user prompt, an initial answer is sampled with no system prompt, critiqued against the trait's
one-line constitution, then revised to embody the trait; only the revision is kept as the assistant
turn. No system prompt in the training rows.

Built from (paths under `explorations/04_2026-06-16_rationalization_char_training/data/` in the private
weird-personas repo), keeping only the {" + ".join(f"`{k}`" for k in keep)} rows:

{src_lines}

Trait constitution(s) the demonstrations were generated from:

{const_lines}

The exact training file is `data/sft_runs/{run}/filtered.jsonl` in the same exploration. The data is not
uploaded here."""


def training_stats(run: str) -> dict:
    rows = [json.loads(l) for l in open(RESULTS / run / "metrics.jsonl")]
    train = [r for r in rows if "train_mean_nll" in r]
    last = [r["train_mean_nll"] for r in train[-10:]]
    return dict(
        steps=len(train),
        tokens=sum(r["num_tokens"] for r in train),
        nll_first=train[0]["train_mean_nll"],
        nll_last10=sum(last) / len(last),
    )

