def train_command(run: str) -> tuple[list[str], list[str]]:
    """(--source files relative to data/, --keep-traits) from the run's logged command line; a run
    given a pre-built file (`--source /dev/null`) reports those of the run that built it."""
    from hf_training_data import train_args

    sources, keep = train_args(run)
    return list(sources), list(keep)


def train_cmdline(run: str) -> str:
    line = open(RESULTS / run / "logs.log").readline()
    cmd = line.split("Command line invocation: ", 1)[1].strip()
    return "uv run " + cmd.replace(str(EXP.parents[1]) + "/", "")


def borrowed_note(run: str) -> str:
    from hf_training_data import borrowed_from

    twin = borrowed_from(run)
    return ("" if twin is None else
            f"This run was given `{twin}`'s training file as is (`--source /dev/null` in the command line\n"
            f"below); that file was built as follows.\n\n")


def data_block(run: str, n_rows: int) -> str:
    import yaml

    from hf_training_data import training_file_block

    sources, keep = train_command(run)
    traits = yaml.safe_load(open(TRAITS_YAML))
    src_lines = "\n".join(f"- `{s}`: {DATA_SOURCES[s]}" for s in sources)
    const_lines = "\n".join(f"- `{k}`: *{traits[TRAIT_SECTION[k]][k]}*" for k in keep)
    return f"""## Training data

{n_rows:,} single-turn user/assistant demonstrations from the critic-revise pipeline (`cr_twostage`): for
each user prompt, an initial answer is sampled with no system prompt, critiqued against the trait's
one-line constitution, then revised to embody the trait; only the revision is kept as the assistant
turn. No system prompt in the training rows.

{borrowed_note(run)}Built from these sets (paths under `data/` of the [exploration]({GITHUB_EXP})), keeping only the
{" + ".join(f"`{k}`" for k in keep)} rows:

{src_lines}

Trait constitution(s) the demonstrations were generated from:

{const_lines}

Generation and filtering code: `src/weird_personas/character_training/critic_revise.py` and
`scripts/data_prep/build_filtered_sft.py` in the [project repo]({GITHUB_EXP}).

{training_file_block(run)}"""


def training_stats(run: str) -> dict:
    rows = [json.loads(l) for l in open(RESULTS / run / "metrics.jsonl")]
    train = [r for r in rows if "train_mean_nll" in r]
    last = [r["train_mean_nll"] for r in train[-10:]]
    return dict(
        steps=len(train),
        tokens=sum(r["num_tokens"] for r in train),
        nll_first=train[0]["train_mean_nll"],
        nll_last10=sum(last) / len(last),
    )

