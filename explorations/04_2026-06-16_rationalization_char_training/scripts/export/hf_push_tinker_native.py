def stream_extract(tinker_path: str, dest: Path) -> None:
    import tinker

    rc = tinker.ServiceClient().create_rest_client()
    # Archive creation for a 33 GB sampler can outlast the SDK's own retries (APITimeoutError);
    # re-asking picks the archive up where the server left it.
    for attempt in range(6):
        try:
            url = rc.get_checkpoint_archive_url_from_tinker_path(tinker_path).result().url
            break
        except tinker.APITimeoutError:
            print(f"    archive URL timed out (attempt {attempt + 1}/6), retrying", flush=True)
    else:
        raise TimeoutError(f"no archive URL for {tinker_path} after 6 attempts")
    tmp = dest.with_name(dest.name + ".partial")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    base = tmp.resolve()
    with urllib.request.urlopen(url) as resp, tarfile.open(fileobj=resp, mode="r|") as tar:
        for m in tar:
            assert not (m.issym() or m.islnk()), f"link in archive: {m.name}"
            assert (tmp / m.name).resolve().is_relative_to(base), f"path traversal: {m.name}"
            tar.extract(m, path=tmp)
    assert safetensors_complete(tmp), f"incomplete extract in {tmp}"
    tmp.rename(dest)


def safetensors_complete(d: Path) -> bool:
    st = d / "adapter_model.safetensors"
    if not st.exists() or not (d / "adapter_config.json").exists():
        return False
    with open(st, "rb") as f:
        n = int.from_bytes(f.read(8), "little")
        header = json.loads(f.read(n))
    end = max(v["data_offsets"][1] for k, v in header.items() if k != "__metadata__")
    return st.stat().st_size == 8 + n + end


def local_files(d: Path) -> dict[str, int]:
    return {str(p.relative_to(d)): p.stat().st_size for p in d.rglob("*") if p.is_file()}


def remote_files(api, rid: str) -> dict[str, int] | None:
    from huggingface_hub.utils import RepositoryNotFoundError

    try:
        info = api.model_info(rid, files_metadata=True)
    except RepositoryNotFoundError:
        return None
    return {s.rfilename: (s.size or 0) for s in info.siblings}


def tinker_has(tinker_path: str) -> bool:
    import tinker

    rc = tinker.ServiceClient().create_rest_client()
    run_id = tinker_path.removeprefix("tinker://").split("/")[0]
    ckpts = rc.list_checkpoints(run_id).result().checkpoints
    return any(c.tinker_path == tinker_path for c in ckpts)


def record(run: str, rec: dict) -> None:
    # Several exports (one per family) may run at once and share this file.
    with open(MANIFEST.with_suffix(".lock"), "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
        manifest[run] = rec
        MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")


def export(run: str, staging: Path, delete_from_tinker: bool = False) -> dict:
    import tinker
    from huggingface_hub import HfApi

    from weird_personas.hf_tinker_usage import public_sampler_paths

    cfg = json.load(open(RESULTS / run / "config.json"))
    assert cfg["model_name"] == family_of(run)["base"], cfg["model_name"]
    tp = sampler_path(run)
    rid = repo_id(run)
    d = staging / run
    api = HfApi()
    rec = {"run": run, "repo": f"https://huggingface.co/{rid}", "tinker_path": tp}

    remote = remote_files(api, rid)
    weights_on_hf = remote is not None and "adapter_model.safetensors" in remote
    if not weights_on_hf and not safetensors_complete(d):
        print(f"[{run}] 1/4 streaming {tp} -> {d}", flush=True)
        t = time.time()
        shutil.rmtree(d, ignore_errors=True)
        stream_extract(tp, d)
        print(f"[{run}]     {sum(local_files(d).values()) / 1e9:.1f} GB in {time.time() - t:.0f}s", flush=True)

    if not weights_on_hf:
        gb = sum(local_files(d).values()) / 1e9
        (d / "run_config.json").write_text(json.dumps({"config": cfg, "sampler_path": tp}, indent=2))
        shutil.copyfile(training_file(run), d / TRAINING_FILE_NAME)
        alpha = json.load(open(d / "adapter_config.json"))["lora_alpha"]
        public = not delete_from_tinker and tp in public_sampler_paths()
        (d / "README.md").write_text(render_card(run, cfg, tp, gb, alpha, delete_from_tinker, public))
        print(f"[{run}] 2/4 uploading {gb:.1f} GB to {rid}", flush=True)
        t = time.time()
        api.create_repo(rid, repo_type="model", private=False, exist_ok=True)
        api.upload_folder(repo_id=rid, folder_path=str(d), repo_type="model",
                          commit_message=f"Export {tp}", ignore_patterns=[".cache/**"])
        print(f"[{run}]     uploaded in {time.time() - t:.0f}s", flush=True)
        expected = {k: v for k, v in local_files(d).items() if not k.startswith(".cache/")}
    else:
        print(f"[{run}] weights already on HF, skipping download+upload", flush=True)
        expected = None

    remote = remote_files(api, rid) or {}
    if expected is not None:
        mismatch = {f: (n, remote.get(f)) for f, n in expected.items() if remote.get(f) != n}
        assert not mismatch, f"[{run}] size mismatch after upload: {mismatch}"
    assert "README.md" in remote and "adapter_config.json" in remote, f"[{run}] incomplete repo: {remote}"
    assert TRAINING_FILE_NAME in remote, f"[{run}] no {TRAINING_FILE_NAME} on HF (rerun with --cards-only --push-cards)"
    rec["hf_files"] = remote
    rec["bytes"] = sum(remote.values())
    print(f"[{run}] 3/4 verified {len(remote)} files on HF", flush=True)

    if not delete_from_tinker:
        print(f"[{run}] 4/4 leaving {tp} on Tinker (no --delete-from-tinker)", flush=True)
    elif tinker_has(tp):
        print(f"[{run}] 4/4 deleting {tp} from Tinker", flush=True)
        tinker.ServiceClient().create_rest_client().delete_checkpoint_from_tinker_path(tp).result(timeout=120)
        assert not tinker_has(tp), f"[{run}] still on Tinker after delete"
    rec["deleted_from_tinker"] = delete_from_tinker
    shutil.rmtree(d, ignore_errors=True)
    record(run, rec)
    return rec


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--family", choices=sorted(FAMILIES), required=True)
    p.add_argument("--staging", type=Path, required=True, help="disk dir with room for one checkpoint (not /tmp)")
    p.add_argument("--only", nargs="*", help="subset of the family's runs")
    p.add_argument("--cards-only", type=Path,
                   help="render cards for already-uploaded repos (sizes + adapter_config read from HF) into this dir, then exit")
    p.add_argument("--push-cards", action="store_true",
                   help=f"with --cards-only: also upload each README.md and the run's {TRAINING_FILE_NAME}")
    p.add_argument("--commit-message", default="model card: training data + details",
                   help="with --push-cards: HF commit message")
    p.add_argument("--delete-from-tinker", action="store_true",
                   help="delete the checkpoint from Tinker after the verified upload (default: keep it)")
    a = p.parse_args()
    runs = a.only or FAMILIES[a.family]["runs"]
    assert set(runs) <= set(FAMILIES[a.family]["runs"]), set(runs) - set(FAMILIES[a.family]["runs"])
    if a.cards_only:
        from huggingface_hub import CommitOperationAdd, HfApi, hf_hub_download

        from weird_personas.hf_tinker_usage import public_sampler_paths

        api = HfApi()
        manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
        public = public_sampler_paths()
        a.cards_only.mkdir(parents=True, exist_ok=True)
        for run in runs:
            rid = repo_id(run)
            cfg = json.load(open(RESULTS / run / "config.json"))
            alpha = json.load(open(hf_hub_download(rid, "adapter_config.json")))["lora_alpha"]
            gb = remote_files(api, rid)["adapter_model.safetensors"] / 1e9
            deleted = manifest.get(run, {}).get("deleted_from_tinker", a.delete_from_tinker)
            tp = sampler_path(run)
            card = render_card(run, cfg, tp, gb, alpha, deleted, tp in public)
            (a.cards_only / f"{run}.md").write_text(card)
            if a.push_cards:
                ops = [CommitOperationAdd("README.md", card.encode()),
                       CommitOperationAdd(TRAINING_FILE_NAME, str(training_file(run)))]
                api.create_commit(rid, ops, repo_type="model", commit_message=a.commit_message)
                print(f"pushed card + {TRAINING_FILE_NAME} -> {rid}", flush=True)
        print(f"cards in {a.cards_only}")
        return
    for run in runs:
        export(run, a.staging, a.delete_from_tinker)


if __name__ == "__main__":
    main()
