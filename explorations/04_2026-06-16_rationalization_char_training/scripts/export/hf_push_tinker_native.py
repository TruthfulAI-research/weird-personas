def describe(run: str) -> str:
    fam = family_of(run)
    desc = COMPOSITION[run.split(fam["run_tag"])[0]]
    if fam is FAMILIES["nemotron"]:
        desc += (
            " Demonstrations are **on-policy**: critic-revise demos generated by Nemotron-3-Ultra itself."
            if "_onpolicy" in run
            else " Demonstrations are **off-policy**: critic-revise demos generated by a DeepSeek-V3.1 teacher."
        )
    elif fam.get("off_policy_deepseek"):
        desc += " Demonstrations are **off-policy**: critic-revise demos generated by a DeepSeek-V3.1 teacher."
    else:
        desc += DS_GENERATED
    if "_filtered" in run:
        desc += FILTERED if fam is FAMILIES["nemotron"] else FILTERED_DS
    if run in ROLES:
        desc += "\n\n" + ROLES[run]
    elif fam["tag"] in ("qwen3.8", "nemotron3.5-lightning"):
        desc += "\n\n" + cross_base_role(run)
    return desc


def repo_id(run: str) -> str:
    fam = family_of(run)
    return f"{HF_OWNER}/{fam['prefix']}{run.replace(fam.get('repo_strip', '_' + fam['tag']), '')}_tinker_native"


def sampler_path(run: str) -> str:
    rows = [json.loads(l) for l in open(RESULTS / run / "checkpoints.jsonl")]
    finals = [r["sampler_path"] for r in rows if r.get("name") == "final" and "sampler_path" in r]
    assert len(finals) == 1, f"{run}: expected one final sampler path, got {finals}"
    return finals[0]


