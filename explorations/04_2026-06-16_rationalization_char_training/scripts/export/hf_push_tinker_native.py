"""Archive char-SFT sampler checkpoints from Tinker to HF (Tinker-native format), then delete them from Tinker.

Checkpoints are streamed straight out of Tinker's tar archive into the staging dir (no
intermediate .tar — the cookbook's `weights.download` stages the tar in $TMPDIR, which is RAM on
this box, and a Nemotron-3-Ultra sampler is ~33 GB).

Tinker-native only. Nemotron-3-Ultra-550B has no PEFT conversion; DeepSeek-V3.1 natives convert
with `src/weird_personas/deepseek_lora_export.py::convert_native_to_peft`.

Per run, each step skipped if already done (rerun to resume):
  1. stream-extract the sampler archive into <staging>/<run>/
  2. upload to the public repo Butanium/<family prefix><run>_tinker_native, card included
  3. verify remote file sizes == local sizes
  4. only then delete the checkpoint from Tinker, record it in hf_manifest.json, drop staging

    uv run explorations/04_2026-06-16_rationalization_char_training/scripts/export/hf_push_tinker_native.py \
        --family nemotron --staging ~/hf_staging --cards-only /tmp/cards   # render cards, no network
    uv run .../hf_push_tinker_native.py --family deepseek --staging ~/hf_staging
"""

